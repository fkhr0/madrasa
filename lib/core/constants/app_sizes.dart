/// Fixed sizes for repeated elements (buttons, icons, avatars).
class AppSizes {
  AppSizes._();

  static const double buttonHeight = 52;

  static const double iconSm = 18;
  static const double iconMd = 22;

  /// Rounded square that holds an icon (see IconBox).
  static const double iconBox = 40;

  static const double avatarSm = 40;
  static const double avatarMd = 48;
  static const double avatarLg = 76;

  /// Content never gets wider than this on tablets.
  static const double maxContentWidth = 640;
}
